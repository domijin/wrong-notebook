export type TranslationTree = typeof translations.en;

/** Recursively fill holes in `override` with values from `base`. */
function withFallback<T>(base: T, override: unknown): T {
    if (base === null || typeof base !== 'object' || Array.isArray(base)) {
        return (override === undefined ? base : override) as T;
    }
    const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
    if (override && typeof override === 'object' && !Array.isArray(override)) {
        for (const [k, v] of Object.entries(override as Record<string, unknown>)) {
            out[k] = k in out ? withFallback(out[k], v) : v;
        }
    }
    return out as T;
}

const resolvedCache = new Map<Language, TranslationTree>();

/** Drop memoized catalogs. Only needed by tests that swap locales at runtime. */
export function clearTranslationCache(): void {
    resolvedCache.clear();
}

/**
 * Return the catalog for `lang`, merged over English so a partially
 * translated locale still resolves every key instead of returning undefined.
 */
export function resolveTranslations(lang: Language): TranslationTree {
    const cached = resolvedCache.get(lang);
    if (cached) return cached;
    const base = translations[FALLBACK_LANGUAGE] as TranslationTree;
    const tree = lang === FALLBACK_LANGUAGE ? base : withFallback(base, translations[lang]);
    resolvedCache.set(lang, tree);
    return tree;
}

/** Narrow an untrusted string (localStorage, query param) to a supported locale. */
export function normalizeLanguage(value: unknown): Language {
    return LANGUAGES.includes(value as Language) ? (value as Language) : 'zh';
}
